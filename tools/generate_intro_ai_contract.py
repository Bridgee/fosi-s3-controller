"""Embed the reviewed English prompt/schema. No network or credential access."""
from pathlib import Path
import json
r=Path(__file__).resolve().parents[1]
prompt=(r/'ai/prompts/openai_intro.txt').read_text()
schema=json.dumps(json.loads((r/'ai/schemas/openai_intro.json').read_text()),separators=(',',':'))
assert prompt.isascii() and ')PROMPT"' not in prompt and ')SCHEMA"' not in schema
out='#pragma once\n// Generated by tools/generate_intro_ai_contract.py; do not edit by hand.\nnamespace orbit_intro_ai {\n'
out+='static const char OpenaiInstructions[]=R"PROMPT('+prompt+')PROMPT";\n'
out+='static const char OpenaiSchema[]=R"SCHEMA('+schema+')SCHEMA";\n}\n'
p=r/'firmware/OrbitS3/intro_ai_contract.h'
if not p.exists() or p.read_text()!=out:p.write_text(out)
