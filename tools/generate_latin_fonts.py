"""Generate pinned Western metadata fonts and ink extents as one validated set."""
import argparse
import json
from pathlib import Path
import re
import tempfile
from font_generation import check_inputs, publish_assets, require, run_converter
from pack_metadata_fonts import pack_font

ROOT = Path(__file__).resolve().parents[1]


def generate(root, font, converter, node):
    info = json.loads((root / "assets/fonts/montserrat-source.json").read_text())
    check_inputs(font, converter, node, info["sha256"], info["converterVersion"])
    metrics, outputs = [], {}
    with tempfile.TemporaryDirectory(prefix="orbit-latin-convert-") as directory:
        for size in info["sizes"]:
            name = f"orbit_metadata_latin_{size}.c"
            staged = Path(directory) / name
            run_converter([node, str(converter), "--font", str(font), "--range", info["ranges"],
                           "--size", str(size), "--bpp", str(info["bpp"]), "--no-kerning", "--no-compress",
                           "--format", "lvgl", "--lv-include", "lvgl.h", "--lv-font-name",
                           f"orbit_metadata_latin_{size}", "-o", str(staged)])
            text = staged.read_text().replace(str(font), "Montserrat-Medium.ttf").replace(str(staged), name)
            text = text.replace('#ifndef ORBIT_METADATA_', '#include "metadata_font.h"\n\n#ifndef ORBIT_METADATA_', 1)
            text = text.replace('= lv_font_get_glyph_dsc_fmt_txt,', '= orbit_metadata_get_glyph_dsc,').replace('= lv_font_get_bitmap_fmt_txt,', '= orbit_metadata_get_bitmap,')
            text = text.replace('static lv_font_fmt_txt_dsc_t font_dsc', 'static const lv_font_fmt_txt_dsc_t font_dsc').replace('.cache = &cache', '.cache = NULL')
            fallback = 'orbit_metadata_12' if size == 14 else 'orbit_metadata_24'
            text = text.replace('.fallback = NULL,', '.fallback = &' + fallback + ',')
            text = re.sub(r'static\s+lv_font_fmt_txt_glyph_cache_t cache;', '', text)
            outputs[root / "firmware/OrbitS3" / name] = pack_font('/* Orbit Metadata Latin; derived from Montserrat 7.200, SIL OFL1.1.\n * Copyright2011 The Montserrat Project Authors. See assets/fonts/. */\n' + text)
            entries = re.findall(r'\.box_w = (\d+), \.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)', text)
            ink = [(int(h) + int(y), -int(y)) for w, h, x, y in entries if int(w) and int(h)]
            require(bool(ink), "No Latin ink extents generated")
            metrics.append((size, max(t for t, b in ink), max(b for t, b in ink)))
    header = '// Generated by tools/generate_latin_fonts.py; ink extents relative to baseline.\n#pragma once\n'
    for size, ascent, descent in metrics:
        header += f'#define ORBIT_LATIN_{size}_ASCENT {ascent}\n#define ORBIT_LATIN_{size}_DESCENT {descent}\n'
    outputs[root / 'firmware/OrbitS3/metadata_latin_metrics.h'] = header
    publish_assets(outputs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True)
    parser.add_argument("--converter", type=Path, required=True)
    parser.add_argument("--node", default="node")
    args = parser.parse_args()
    try:
        generate(ROOT, args.font, args.converter, args.node)
    except (ValueError, OSError) as error:
        parser.exit(1, str(error) + "\n")
    print("PASS: validated pinned Western fonts and unchanged ink extents generated")


if __name__ == "__main__":
    main()
